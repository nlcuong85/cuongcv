export type WritingMode = "application" | "academic" | "blog" | "work" | "social" | "general";

export type CheckerIssue = {
  code: string;
  severity: "error" | "warning" | "note";
  message: string;
  suggestion: string;
};

export type CheckerResult = {
  ok: boolean;
  mode: WritingMode;
  riskLevel: "low" | "medium" | "high";
  summary: string;
  issues: CheckerIssue[];
  revisionPlan: string[];
  doNotDo: string[];
  privacy: {
    stored: false;
    rawTextLogged: false;
    note: string;
  };
};

